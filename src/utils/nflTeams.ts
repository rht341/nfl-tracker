export const TEAM_BY_ID: Record<string, NFLTeamStatic> = Object.fromEntries(
  NFL_TEAMS.map((t) => [t.id, t])
);

export const TEAM_BY_ABBR: Record<string, NFLTeamStatic> = Object.fromEntries(
  NFL_TEAMS.map((t) => [t.abbr.toUpperCase(), t])
);

// Handle common ESPN abbreviation aliases (like WAS -> WSH, JAC -> JAX, OAK -> LV, LA -> LAR)
TEAM_BY_ABBR['WAS'] = TEAM_BY_ABBR['WSH'];
TEAM_BY_ABBR['JAC'] = TEAM_BY_ABBR['JAX'];
TEAM_BY_ABBR['OAK'] = TEAM_BY_ABBR['LV'];
TEAM_BY_ABBR['LA'] = TEAM_BY_ABBR['LAR'];

export function getTeamByIdOrAbbr(idOrAbbr?: string): NFLTeamStatic {
  if (!idOrAbbr) return NFL_TEAMS[0];
  const byId = TEAM_BY_ID[String(idOrAbbr)];
  if (byId) return byId;
  const byAbbr = TEAM_BY_ABBR[String(idOrAbbr).toUpperCase()];
  if (byAbbr) return byAbbr;
  return NFL_TEAMS[0];
}
